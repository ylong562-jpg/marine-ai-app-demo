improved = 0
failed = []

for sy in data:
    sid = sy['id']
    if sid in refinements and sy.get('geo_level') == 'location':
        info = refinements[sid]
        q = info['query']
        url = 'https://photon.komoot.io/api/?q=' + urllib.parse.quote(q) + '&limit=1'
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        try:
            with urllib.request.urlopen(req, timeout=12) as resp:
                res = json.loads(resp.read().decode())
                if res.get('features') and len(res['features']) > 0:
                    coords = res['features'][0]['geometry']['coordinates']
                    new_lat, new_lng = float(coords[1]), float(coords[0])
                    old_lat, old_lng = sy['lat'], sy['lng']
                    if abs(new_lat - old_lat) < 0.02 and abs(new_lng - old_lng) < 0.02:
                        print(f"[{sid}] {sy['name']}: 坐标相近，跳过")
                    else:
                        sy['lat'] = new_lat
                        sy['lng'] = new_lng
                        sy['geo_level'] = 'precise'
                        improved += 1
                        print(f"[{sid}] {sy['name']}: {old_lat:.4f},{old_lng:.4f} -> {new_lat:.6f},{new_lng:.6f}")
                else:
                    failed.append(sy['name'])
                    print(f"[{sid}] {sy['name']}: 无结果")
        except Exception as e:
            failed.append(sy['name'])
            print(f"[{sid}] {sy['name']}: 失败 ({e})")
        time.sleep(0.15)

with open('backend/data/shipyards_data.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print(f"\n完成: 精确化了 {improved} 个, 失败 {len(failed)} 个")
if failed:
    print('失败列表:', failed)
