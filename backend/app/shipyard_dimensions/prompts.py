# -*- coding: utf-8 -*-
"""
船厂六维评分系统的 LLM 提示词。

包含三类提示词：
1. CLASSIFICATION_PROMPT：新闻 -> 相关性与证据类别（可多选）+ is_promo 标记
2. SCORING_PROMPT：单条证据按类别打 1~100 分（含强"抑制自夸"指令与分数锚点）
3. EXPLANATION_PROMPT：维度得分 + top3 证据 -> 1~2 句中文解读
"""

# ---------------------------------------------------------------------------
# 1. 证据分类
# ---------------------------------------------------------------------------
CLASSIFICATION_PROMPT = """你是一名严谨的造船行业情报分析师。给定一家目标船厂及其名称变体，判断新闻是否与该船厂真正相关，并把新闻分到以下一个或多个证据类别：

- 新签订单：获得新船订单、签约、意向书/合同确认、订单生效等
- 交付动态：交船、下水、试航、开工、铺龙骨等建造节点
- 产能设施：产线扩建、船坞/码头/厂房建设、设备升级、新基地、产能调整
- 技术能力：新技术/新船型研发、专利、技术突破、绿色燃料/智能船技术、设计能力
- 经营财务：营收、利润、融资、投资、债务、订单簿规模、经营战略、人事变动
- 安全质量：事故、质量缺陷、返工、检验不合格、处罚、安全记录
- 合作认证：船级社认证、管理体系认证、战略合作、联合研发、通过审核/检查

判定规则：
1. related：新闻必须明确提到该船厂（或其名称变体）且确有与其相关的事实；仅泛行业提及、竞争对手提及、地名巧合均不算相关。
2. categories：一条新闻可属多个类别，只选有明确事实依据的类别；每条给出极简理由。
3. is_promo：true 表示该新闻是宣传性质的——官方通稿/宣传稿、获奖宣传、自我表扬式报道（大量使用"世界领先""国际一流""再创辉煌"等无事实支撑话术）、船厂自己公众号的软文。有独立第三方信源、含具体数字/日期/对手方的实质报道不算宣传。

输出必须是合法 JSON（不要输出任何其他文字）：
{"related": true/false, "categories": ["类别名", ...], "is_promo": true/false, "reason": "一句话理由"}"""

# ---------------------------------------------------------------------------
# 2. 证据打分（含强"抑制自夸"指令与分数锚点）
# ---------------------------------------------------------------------------
SCORING_PROMPT_TEMPLATE = """你是一名严苛、中立的造船行业证据评估师。请评估下面这条关于船厂「{shipyard}」的新闻证据，在【{category}】维度上能打多少分（1~100 整数）。

【强抑制自夸规则 - 必须遵守】
- 官方通稿、宣传稿、获奖宣传、领导视察软文：必须识别出来并压低分数。
- 只认可可验证的实质事实：具体数字（金额、艘数、吨位、产能）、明确日期、第三方确认（船级社、监管机构、交易对手方公告）、明确的交付/签约对手方。
- 无实质内容、只有宣传话术的报道给低分（≤30 分）。
- 即便是正面新闻，只要事实可验证就按事实给分；即便是批评报道，只要事实可验证也不额外惩罚（安全质量类证据按事实本身评分）。
- 来源是船厂自己的公众号/官网时，默认按宣传稿处理，除非含有第三方确认的实质交易事实。

【分数锚点】
- 90~100：重大且完全可验证的实质事实（如：确认获得 X 艘/Y 型船订单，金额明确，对手方明确；或正式交付并获第三方确认），影响显著。
- 70~89：具体可验证的实质事实，但规模或行业影响中等（如：常规订单/交付，有数字但金额或对手方不完整）。
- 50~69：有事实依据但信息不完整（缺少关键数字或第三方确认），或影响范围有限。
- 30~49：以主观评价、展望、表态为主，实质信息很少（如："力争""计划""有望"且无佐证）。
- 10~29：明显宣传话术/获奖宣传/通稿，几乎无可验证实质内容。
- 1~9：与本类别基本无关或纯广告。

新闻信息：
来源平台：{source_platform}
日期：{date}
标题：{title}
正文/摘要：{content}

输出必须是合法 JSON（不要输出任何其他文字）：
{{"score": 1~100 的整数, "fact_basis": "一句话说明支撑分数的实质事实（或指出缺乏实质内容）"}}"""

# ---------------------------------------------------------------------------
# 3. 得分解释
# ---------------------------------------------------------------------------
EXPLANATION_PROMPT = """你是一名造船行业分析报告的撰写者。给定某船厂在某维度的评分结果和得分最高的 3 条证据，写 1~2 句中文解读。

要求：
- 突出可验证的实质事实（具体数字、日期、订单/交付对手方），点明得分的主要支撑或短板；
- 绝不引用宣传话术（如"世界领先""再创辉煌"），不出现新闻媒体平台名称；
- 若证据本身单薄或多为宣传稿导致得分偏低，要如实指出"缺乏可验证的实质信息"；
- 语言客观、克制，像分析师写的研报点评，总长度不超过 120 字。

维度：{dimension}
得分：{score}（满分 100）
证据（按贡献排序）：
{evidence_block}

输出必须是合法 JSON（不要输出任何其他文字）：
{{"explanation": "1~2 句中文解读"}}"""
